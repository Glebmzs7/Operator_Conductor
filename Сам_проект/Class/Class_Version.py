"""
Версия — это просто СТРОКА, которую разработчик придумывает и полностью контролирует сам (любой
текст, хоть "HJDF3123Hj0"), плюс ОДНО число в конце — номер пуша (push_count), который видит и
меняет только сам демон.

Раньше вся версия целиком обязана была совпадать со строгим форматом
(Stable,StablePatch.Beta,BetaPush...) — и любое отклонение (например тег, поправленный руками
не по формату) роняло программу с ValueError. Потом требование ослабили до "число после ПОСЛЕДНЕЙ
ЗАПЯТОЙ" — но запятая как разделитель была жёстко зашита, и обойти её (свой знак-разделитель,
например дефис в "GitAvto-0") было нельзя.

С 23.09 разделитель вообще не имеет значения: push_count — это ЛЮБАЯ цепочка цифр в самом конце
строки, а всё, что было ДО неё (включая сам разделитель — запятую, дефис, точку, что угодно, или
вообще ничего) — это и есть префикс, дальше не разбирается. build_tag() поэтому просто дописывает
число к переданному префиксу, ничего от себя не добавляя — какой разделитель нужен, тот и должен
быть уже в префиксе (обычно он там и оказывается сам, потому что split_prefix_and_push при разборе
существующего тега его туда и относит). Если в конце строки цифр нет вообще — считаем, что пушей
ещё не было (push_count = 0), и НЕ падаем.
"""

import re
from typing import Tuple

_TRAILING_DIGITS = re.compile(r"(\d+)$")


def split_prefix_and_push(tag: str) -> Tuple[str, int]:
    """'2,1.5,3.7,4,9' -> ('2,1.5,3.7,4,', 9) — разделитель (запятая) остаётся частью префикса.
    'GitAvto-7' -> ('GitAvto-', 7). Если в конце строки нет цифр — весь тег считается префиксом,
    а push_count = 0."""
    tag = tag.strip()
    m = _TRAILING_DIGITS.search(tag)
    if m:
        return tag[:m.start()], int(m.group(1))
    return tag, 0


def next_tag(tag: str) -> str:
    """Тег для следующего автоматического пуша — тот же префикс (вместе с разделителем, если он
    был), push_count + 1."""
    prefix, push_count = split_prefix_and_push(tag)
    return build_tag(prefix, push_count + 1)


def build_tag(prefix: str, push_count: int = 0) -> str:
    return f"{prefix}{push_count}"


if __name__ == "__main__":
    assert split_prefix_and_push("2,1.5,3.7,4,9") == ("2,1.5,3.7,4,", 9)
    assert next_tag("2,1.5,3.7,4,9") == "2,1.5,3.7,4,10"
    assert build_tag("2,1.5,3.7,4,", 9) == "2,1.5,3.7,4,9"

    # Свой знак-разделитель (не запятая) — теперь просто работает, ничего не зашито
    assert split_prefix_and_push("GitAvto-7") == ("GitAvto-", 7)
    assert next_tag("GitAvto-7") == "GitAvto-8"
    assert build_tag("GitAvto-", 0) == "GitAvto-0"

    # Текст без цифр на конце — весь тег считается префиксом, push_count = 0, не падаем
    assert split_prefix_and_push("HJDF3123Hj") == ("HJDF3123Hj", 0)
    assert next_tag("HJDF3123Hj") == "HJDF3123Hj1"

    # Старый тег с буквой статуса (до отказа от статусов) — тоже просто часть префикса, не падает
    prefix, push = split_prefix_and_push("G0,0.0,0.7,0,2")
    assert (prefix, push) == ("G0,0.0,0.7,0,", 2)

    print("version.py: самопроверка пройдена")
